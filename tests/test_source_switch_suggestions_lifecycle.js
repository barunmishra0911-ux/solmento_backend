import assert from "node:assert/strict";
import { pool } from "../src/config/database.js";
import {
  getPublicWidgetConfig,
  sendPublicWidgetMessage,
  savePublicLead,
  publishChatbotBuilder,
} from "../src/services/chatbotService.js";
import { executeCrawlJob } from "../src/services/crawlJobService.js";
import { computeSourceFingerprint } from "../src/services/chatbotKnowledgeService.js";

async function runTest() {
  console.log("=== TEST SUITE: Website Source Switch Suggestions Lifecycle ===");

  const chatbotId = 81;
  const tenantId = 7;
  const publicId = "813b2820-8177-4011-bf46-2ed2122e4d3f";
  const jutUrl = "https://jutranchi.ac.in/sitemap.xml";

  // [1] Verify current JUT configuration on Chatbot 81
  console.log("\n[1] Verifying current Chatbot 81 JUT configuration and suggestions...");
  const initialWidgetConfig = await getPublicWidgetConfig(publicId);
  const initialSuggestions = initialWidgetConfig.config?.suggestedQuestions || [];
  console.log("  Initial Suggestions:", initialSuggestions);

  assert(initialSuggestions.length > 0, "Chatbot 81 should have active suggestions for JUT");
  const initialText = initialSuggestions.join(" ").toLowerCase();
  assert(!initialText.includes("django"), "Chatbot 81 initial suggestions must contain NO Django mentions");
  assert(
    initialText.includes("university") || initialText.includes("jharkhand"),
    "Chatbot 81 suggestions must be JUT-specific",
  );
  console.log("  ✓ JUT suggestions verified, 0 Django leakage.");

  // [2] Test visitor question with M.Tech admission
  console.log("\n[2] Testing visitor question 'How can someone get admission in M.Tech?' on JUT...");
  const visitorId = "jut-test-" + Date.now();
  await savePublicLead({
    publicId,
    visitorId,
    fields: { name: "JUT Candidate", email: "jut@example.com", phone: "+919876543210" },
  });

  const response1 = await sendPublicWidgetMessage({
    publicId,
    visitorId,
    text: "How can someone get admission in M.Tech?",
  });

  console.log("  Reply:", response1.reply.slice(0, 140) + "...");
  console.log("  Suggestions:", response1.suggestions);
  const turn1Text = (response1.reply + " " + (response1.suggestions || []).join(" ")).toLowerCase();
  assert(!turn1Text.includes("django"), "Turn 1 must have 0 Django mentions");
  assert(
    (response1.suggestions || []).some(
      (s) =>
        s.toLowerCase().includes("university") ||
        s.toLowerCase().includes("jharkhand") ||
        s.toLowerCase().includes("m.tech") ||
        s.toLowerCase().includes("admission"),
    ),
    "Turn 1 suggestions must be JUT-specific",
  );
  console.log("  ✓ Turn 1 response and suggestions strictly grounded in JUT.");

  // [3] Simulate Source Switch to a new website
  console.log("\n[3] Simulating website source switch in Chatbot Builder to new domain...");
  const [[cbRow]] = await pool.execute(
    "SELECT name, status, config_json, published_config_json FROM chatbots WHERE id = ? AND tenant_id = ?",
    [chatbotId, tenantId],
  );
  const existingConfig = typeof cbRow.config_json === "string" ? JSON.parse(cbRow.config_json) : cbRow.config_json;
  const switchedConfig = {
    ...existingConfig,
    websiteUrl: "https://example-new-polytechnic.edu/sitemap.xml",
    autoGeneratedQuestions: true,
  };

  await publishChatbotBuilder({
    id: chatbotId,
    tenantId,
    userId: 1,
    name: cbRow.name,
    status: cbRow.status,
    config: switchedConfig,
    changes: ["Updated website to new polytechnic domain"],
  });

  // [4] Verify immediate invalidation on source switch
  console.log("\n[4] Verifying immediate cache invalidation and neutral state during reconfiguring...");
  const [[crawlStateAfterSwitch]] = await pool.execute(
    "SELECT source_fingerprint, active_source_fingerprint, last_check_status FROM chatbot_crawl_states WHERE chatbot_id = ?",
    [chatbotId],
  );
  assert.equal(
    crawlStateAfterSwitch.last_check_status,
    "RECONFIGURING",
    "Crawl state must immediately become RECONFIGURING",
  );
  assert.equal(
    crawlStateAfterSwitch.active_source_fingerprint,
    null,
    "active_source_fingerprint must be null during reconfiguring",
  );

  const [[dbAfterSwitch]] = await pool.execute(
    "SELECT config_json, published_config_json FROM chatbots WHERE id = ?",
    [chatbotId],
  );
  const pubCfgAfterSwitch = typeof dbAfterSwitch.published_config_json === "string"
    ? JSON.parse(dbAfterSwitch.published_config_json)
    : dbAfterSwitch.published_config_json;
  assert.deepEqual(
    pubCfgAfterSwitch.suggestedQuestions,
    [],
    "published_config_json.suggestedQuestions must be immediately cleared to []",
  );

  const widgetConfigDuringReconfig = await getPublicWidgetConfig(publicId);
  assert.deepEqual(
    widgetConfigDuringReconfig.config?.suggestedQuestions,
    [],
    "getPublicWidgetConfig must return empty suggestions [] while reconfiguring (0 previous source leakage)",
  );

  const responseDuringReconfig = await sendPublicWidgetMessage({
    publicId,
    visitorId,
    text: "How do I apply?",
  });
  assert.equal(responseDuringReconfig.intent, "SYSTEM_NOTIFICATION");
  assert.deepEqual(
    responseDuringReconfig.suggestions,
    [],
    "sendPublicWidgetMessage must return [] suggestions during reconfiguring",
  );
  console.log("  ✓ Source switch immediately invalidated cached suggestions and entered neutral state.");

  // [5] Revert back to JUT and re-sync JUT crawl state & suggestions
  console.log("\n[5] Restoring JUT website URL and completing crawl...");
  const restoredConfig = {
    ...existingConfig,
    websiteUrl: jutUrl,
    autoGeneratedQuestions: true,
  };
  await publishChatbotBuilder({
    id: chatbotId,
    tenantId,
    userId: 1,
    name: cbRow.name,
    status: cbRow.status,
    config: restoredConfig,
    changes: ["Restored JUT website"],
  });

  const jutFp = computeSourceFingerprint(jutUrl);
  // Mark completed with active JUT fingerprint
  await pool.execute(
    `UPDATE chatbot_crawl_states
        SET last_check_status = 'COMPLETED',
            source_fingerprint = ?,
            active_source_fingerprint = ?,
            last_successful_crawl_at = NOW()
      WHERE chatbot_id = ?`,
    [jutFp, jutFp, chatbotId],
  );

  // Restore JUT suggestions in published config
  await pool.execute(
    `UPDATE chatbots
        SET config_json = JSON_SET(config_json, '$.suggestedQuestions', JSON_ARRAY(
              JSON_OBJECT('id', 'question-jut-1', 'text', 'How do I contact the university?'),
              JSON_OBJECT('id', 'question-jut-2', 'text', 'Where can I find screen reader access?'),
              JSON_OBJECT('id', 'question-jut-3', 'text', "What is the university's vision and mission?"),
              JSON_OBJECT('id', 'question-jut-4', 'text', 'Where is Jharkhand University of Technology?')
            )),
            published_config_json = JSON_SET(published_config_json, '$.suggestedQuestions', JSON_ARRAY(
              JSON_OBJECT('id', 'question-jut-1', 'text', 'How do I contact the university?'),
              JSON_OBJECT('id', 'question-jut-2', 'text', 'Where can I find screen reader access?'),
              JSON_OBJECT('id', 'question-jut-3', 'text', "What is the university's vision and mission?"),
              JSON_OBJECT('id', 'question-jut-4', 'text', 'Where is Jharkhand University of Technology?')
            ))
      WHERE id = ?`,
    [chatbotId],
  );

  const restoredWidgetConfig = await getPublicWidgetConfig(publicId);
  const finalSuggestions = restoredWidgetConfig.config?.suggestedQuestions || [];
  console.log("  Restored JUT Suggestions:", finalSuggestions);
  assert(finalSuggestions.length > 0, "Restored suggestions should be present");
  const finalSuggestionsText = finalSuggestions.join(" ").toLowerCase();
  assert(!finalSuggestionsText.includes("django"), "Must have 0 Django mentions");
  assert(
    finalSuggestionsText.includes("university") || finalSuggestionsText.includes("jharkhand"),
    "Must be JUT-specific",
  );
  console.log("  ✓ JUT suggestions successfully restored with 0 stale leakage.");

  console.log("\n=== ALL SOURCE SWITCH SUGGESTIONS LIFECYCLE TESTS PASSED! ===");
  process.exit(0);
}

runTest().catch((err) => {
  console.error("Test failed:", err);
  process.exit(1);
});
